/**
 * The tokens a theme varies — every key `createTheme` overrides per mode.
 *
 * Exported because it is also the boundary of what a PRODUCT theme may set. A
 * custom property inherits, and CSS has no way to un-inherit one, so a token a
 * brand sets would keep applying inside a nested region that opted back out.
 * The themed set is the one a theme root can re-establish wholesale, which is
 * what makes the reset complete rather than partial. Everything else a brand
 * wants to change — a radius, a weight, a border width — is a component recipe,
 * which `@scope` bounds properly.
 */
export type ThemedTokenName = keyof typeof lightThemeValues;
