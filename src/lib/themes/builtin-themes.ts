const BUILTIN_THEME_BASE_TOKENS: Record<
  ThemeModeName,
  BuiltinThemeTokenValues
> = {
  light: {
    ...PRESET_THEME_TOKENS.light,
    ...PRESET_EXTENDED_THEME_TOKENS.light,
  },
  dark: {
    ...PRESET_THEME_TOKENS.dark,
    ...PRESET_EXTENDED_THEME_TOKENS.dark,
  },
};

function createBuiltinTheme(args: {
  id: string;
  name: string;
  description: string;
  baseMode: ThemeModeName;
  overrides: Partial<BuiltinThemeTokenValues>;
}): CustomThemeDefinition {
  return {
    id: args.id,
    name: args.name,
    description: args.description,
    baseMode: args.baseMode,
    version: "1.0.0",
    author: "Stave",
    tokens: {
      ...BUILTIN_THEME_BASE_TOKENS[args.baseMode],
      ...args.overrides,
    },
  };
}

