#!/usr/bin/env node

import { execFileSync, spawnSync } from "node:child_process";
import { readFileSync, lstatSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const CODE_EXTENSIONS = new Set([
  ".ts",
  ".tsx",
  ".js",
  ".jsx",
  ".mts",
  ".cts",
  ".mjs",
  ".cjs",
  ".css",
  ".scss",
  ".html",
]);
const DOC_EXTENSIONS = new Set([".md", ".mdx", ".txt"]);
const CONFIG_EXTENSIONS = new Set([
  ".json",
  ".jsonc",
  ".yaml",
  ".yml",
  ".toml",
  ".plist",
]);
const LIMITS = [500, 1000, 2000];
const SELECTION = {
  sourceRoots: ["src/", "electron/", "server/", "site/"],
  testRoots: ["tests/", "**/__tests__/", "*.test.*", "*.spec.*"],
  docsRoots: ["docs/", "skills/", "root Markdown/text"],
  toolingRoots: [
    "scripts/",
    "config/",
    ".github/",
    "build/",
    "root config/code",
  ],
  codeExtensions: [...CODE_EXTENSIONS],
  docExtensions: [...DOC_EXTENSIONS],
  configExtensions: [...CONFIG_EXTENSIONS],
};

function usage() {
  return `Usage: node scripts/codebase-structure.mjs [--json] [--ref <commit>]

Inventory tracked and untracked, non-ignored text files in this checkout.
--ref <commit> inventories a Git tree instead, for a stable before/after comparison.
--json emits deterministic machine-readable output with per-file rows.

Source roots: src/, electron/, server/, site/ (code extensions).
Tests: tests/, __tests__/, and *.test.* or *.spec.* code files.
Docs: docs/, skills/, and root Markdown/text files.
Tooling: scripts/, config/, .github/, build/, and root code/config files.
Supported extensions are listed under selection in JSON output; binary assets,
lockfiles, and unrelated text formats are excluded.

Physical lines count a final unterminated line and exclude an empty final line.
Source thresholds exclude declarations and generated files. The existing
check:max-lines-ratchet remains the enforcing guardrail.`;
}

function parseArgs(args) {
  let json = false;
  let ref;
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--json") json = true;
    else if (arg === "--ref" && args[index + 1]) ref = args[++index];
    else if (arg === "--help" || arg === "-h") return { help: true };
    else throw new Error(`Unknown or incomplete argument: ${arg}`);
  }
  return { json, ref };
}

function git(args, options = {}) {
  return execFileSync("git", args, { cwd: process.cwd(), ...options });
}

function repoRoot() {
  return git(["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
}

function categoryFor(file) {
  const extension = path.posix.extname(file);
  const basename = path.posix.basename(file);
  if (
    file.startsWith("tests/") ||
    file.includes("/__tests__/") ||
    /\.(test|spec)\.[cm]?[jt]sx?$/.test(file)
  ) {
    return CODE_EXTENSIONS.has(extension) ? "tests" : null;
  }
  if (
    file.startsWith("docs/") ||
    file.startsWith("skills/") ||
    (!file.includes("/") && DOC_EXTENSIONS.has(extension))
  ) {
    return DOC_EXTENSIONS.has(extension) ? "docs" : null;
  }
  if (
    file.startsWith("scripts/") ||
    file.startsWith("config/") ||
    file.startsWith(".github/") ||
    file.startsWith("build/") ||
    !file.includes("/")
  ) {
    return CODE_EXTENSIONS.has(extension) ||
      CONFIG_EXTENSIONS.has(extension) ||
      DOC_EXTENSIONS.has(extension) ||
      basename === "Dockerfile" ||
      basename === "CODEOWNERS"
      ? "tooling"
      : null;
  }
  if (SELECTION.sourceRoots.some((root) => file.startsWith(root))) {
    return CODE_EXTENSIONS.has(extension) ? "source" : null;
  }
  return null;
}

function classification(file, content) {
  if (/\.d\.[cm]?ts$/.test(file)) return "declaration";
  if (/(^|\/)(generated|__generated__)(\/|$)|[.-]generated\.[^/]+$/.test(file))
    return "generated";
  const preamble = content
    .subarray(0, 1024)
    .toString("utf8")
    .split("\n")
    .slice(0, 8)
    .join("\n");
  if (
    /^\s*(?:\/\/|\/\*+|\*|#|<!--)\s*(?:@generated\b|auto[- ]generated\b|generated by\b)/im.test(
      preamble,
    )
  )
    return "generated";
  return "handwritten";
}

function lineCount(content) {
  if (content.length === 0) return 0;
  let count = 0;
  for (const byte of content) if (byte === 10) count += 1;
  return count + (content.at(-1) === 10 ? 0 : 1);
}

function workingFiles(root) {
  const names = git(
    ["ls-files", "--cached", "--others", "--exclude-standard", "-z"],
    { cwd: root },
  )
    .toString("utf8")
    .split("\0")
    .filter(Boolean);
  return [...new Set(names)].sort().flatMap((file) => {
    const category = categoryFor(file);
    if (!category) return [];
    const absolute = path.join(root, file);
    let stats;
    try {
      stats = lstatSync(absolute, { throwIfNoEntry: false });
    } catch {
      return [];
    }
    if (!stats?.isFile()) return [];
    return [{ path: file, category, content: readFileSync(absolute) }];
  });
}

function treeFiles(root, ref) {
  const tree = git(["rev-parse", "--verify", `${ref}^{tree}`], {
    cwd: root,
    encoding: "utf8",
  }).trim();
  const entries = git(["ls-tree", "-rz", tree], { cwd: root })
    .toString("utf8")
    .split("\0")
    .filter(Boolean)
    .flatMap((entry) => {
      const match = /^(\d+) blob ([0-9a-f]+)\t([\s\S]+)$/.exec(entry);
      if (!match || match[1] === "120000") return [];
      const category = categoryFor(match[3]);
      return category ? [{ path: match[3], category, hash: match[2] }] : [];
    })
    .sort((a, b) => a.path.localeCompare(b.path, "en"));
  const result = spawnSync("git", ["cat-file", "--batch"], {
    cwd: root,
    input: entries.map(({ hash }) => hash).join("\n") + "\n",
    maxBuffer: 256 * 1024 * 1024,
  });
  if (result.error || result.status !== 0)
    throw result.error ?? new Error(result.stderr.toString("utf8"));
  let offset = 0;
  return entries.map(({ path: file, category }) => {
    const newline = result.stdout.indexOf(10, offset);
    const header = result.stdout.toString("utf8", offset, newline);
    const size = Number(header.split(" ").at(-1));
    if (newline < 0 || !Number.isSafeInteger(size))
      throw new Error(`Invalid Git object for ${file}`);
    const start = newline + 1;
    const content = result.stdout.subarray(start, start + size);
    offset = start + size + 1;
    return { path: file, category, content };
  });
}

function summarize(files, scope) {
  const rows = files.map(({ path: file, category, content }) => ({
    path: file,
    category,
    kind: classification(file, content),
    lines: lineCount(content),
  }));
  const categories = Object.fromEntries(
    ["source", "tests", "docs", "tooling"].map((category) => [
      category,
      { files: 0, lines: 0 },
    ]),
  );
  const kinds = Object.fromEntries(
    ["handwritten", "generated", "declaration"].map((kind) => [
      kind,
      { files: 0, lines: 0 },
    ]),
  );
  const directories = new Map();
  const thresholds = Object.fromEntries(
    LIMITS.map((limit) => [`over${limit}`, 0]),
  );
  for (const row of rows) {
    categories[row.category].files += 1;
    categories[row.category].lines += row.lines;
    kinds[row.kind].files += 1;
    kinds[row.kind].lines += row.lines;
    if (row.category !== "source" || row.kind !== "handwritten") continue;
    for (const limit of LIMITS)
      if (row.lines > limit) thresholds[`over${limit}`] += 1;
    const directory = path.posix.dirname(row.path);
    const stats = directories.get(directory) ?? {
      path: directory,
      files: 0,
      lines: 0,
    };
    stats.files += 1;
    stats.lines += row.lines;
    directories.set(directory, stats);
  }
  const bySize = (a, b) =>
    b.lines - a.lines || a.path.localeCompare(b.path, "en");
  return {
    scope,
    selection: SELECTION,
    totals: {
      files: rows.length,
      lines: rows.reduce((total, row) => total + row.lines, 0),
    },
    categories,
    kinds,
    sourceThresholds: thresholds,
    largestHandwrittenSource: rows
      .filter((row) => row.category === "source" && row.kind === "handwritten")
      .sort(bySize)
      .slice(0, 20),
    crowdedSourceDirectories: [...directories.values()]
      .sort(
        (a, b) =>
          b.files - a.files ||
          b.lines - a.lines ||
          a.path.localeCompare(b.path, "en"),
      )
      .slice(0, 20),
    files: rows,
  };
}

function formatText(report) {
  const lines = [
    `Codebase structure (${report.scope}): ${report.totals.files} files, ${report.totals.lines} physical lines`,
  ];
  for (const [category, stats] of Object.entries(report.categories))
    lines.push(`  ${category}: ${stats.files} files, ${stats.lines} lines`);
  lines.push(
    `  generated: ${report.kinds.generated.files} files, ${report.kinds.generated.lines} lines; declarations: ${report.kinds.declaration.files} files, ${report.kinds.declaration.lines} lines`,
  );
  lines.push(
    `Handwritten source over 500/1000/2000 lines: ${Object.values(report.sourceThresholds).join("/")}`,
  );
  lines.push("Largest handwritten source files:");
  for (const row of report.largestHandwrittenSource.slice(0, 10))
    lines.push(`  ${String(row.lines).padStart(5)}  ${row.path}`);
  lines.push("Crowded source directories (immediate files):");
  for (const row of report.crowdedSourceDirectories.slice(0, 10))
    lines.push(`  ${String(row.files).padStart(4)} files  ${row.path}`);
  return lines.join("\n");
}

try {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    console.log(usage());
  } else {
    const root = repoRoot();
    const report = summarize(
      options.ref ? treeFiles(root, options.ref) : workingFiles(root),
      options.ref ? `ref:${options.ref}` : "working-tree",
    );
    console.log(
      options.json ? JSON.stringify(report, null, 2) : formatText(report),
    );
  }
} catch (error) {
  console.error(`codebase-structure: ${error.message}`);
  process.exitCode = 1;
}
